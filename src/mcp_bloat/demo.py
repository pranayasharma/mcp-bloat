def _tool_source(name: str, description: str, params: list) -> str:
    lines = ["@server.tool()", f"def {name}("]
    for param, ptype, pdesc, default in params:
        if default is None:
            lines.append(
                f"    {param}: Annotated[{ptype}, Field(description={pdesc!r})],"
            )
        else:
            lines.append(
                f"    {param}: Annotated[{ptype}, Field(description={pdesc!r})]"
                f" = {default},"
            )
    lines.append("):")
    lines.append(f"    {description!r}")
    lines.append(f'    return {{"status": "ok", "tool": {name!r}}}')
    lines.append("")
    lines.append("")
    return "\n".join(lines)


def _large_tool_specs() -> list:
    specs = []
    combos = []
    for resource, flavor in _LARGE_RESOURCES.items():
        for action in ("get", "list", "create", "update", "delete"):
            combos.append((resource, flavor, action))
    combos = combos[:46]
    combos += [(r, _LARGE_RESOURCES[r], "search") for r in ("issue", "pull_request", "code_search", "user")]
    for resource, flavor, action in combos[:50]:
        name = f"{action}_{resource}"
        description = _LARGE_ACTIONS[action].format(res=f"a {flavor}") + _USAGE_NOTE
        specs.append((name, description, _LARGE_PARAMS[action]))
    return specs


def build_demo_server_source() -> str:
    parts = [_HEADER]
    parts.append('if sys.argv[1] == "small":')
    for name, desc, params in SMALL_TOOLS:
        parts.append("    " + _tool_source(name, desc, params).replace("\n", "\n    ").rstrip())
    parts.append('elif sys.argv[1] == "medium":')
    for name, desc, params in MEDIUM_TOOLS:
        parts.append("    " + _tool_source(name, desc, params).replace("\n", "\n    ").rstrip())
    parts.append("else:  # large")
    for name, desc, params in _large_tool_specs():
        parts.append("    " + _tool_source(name, desc, params).replace("\n", "\n    ").rstrip())
    parts.append("")
    parts.append('if __name__ == "__main__":')
    parts.append("    server.run()")
    parts.append("")
    return "\n".join(parts)


def run_demo(
    timeout: float = DEFAULT_TIMEOUT,
) -> tuple[list[ServerAudit], list[DiscoveryWarning]]:
    """Generate the demo servers, audit them, and return the results."""
    with tempfile.TemporaryDirectory(prefix="mcp-bloat-demo-") as tmp:
        tmp_path = Path(tmp)
        script = tmp_path / "demo_server.py"
        script.write_text(build_demo_server_source(), encoding="utf-8")
        config = {
            "mcpServers": {
                "notes-lite": {
                    "command": sys.executable,
                    "args": [str(script), "small"],
                },
                "dev-toolbox": {
                    "command": sys.executable,
                    "args": [str(script), "medium"],
                },
                "mega-api": {
                    "command": sys.executable,
                    "args": [str(script), "large"],
                },
            }
        }
        config_path = tmp_path / "mcp.json"
        config_path.write_text(json.dumps(config, indent=2), encoding="utf-8")

        discovered = load_config_file(config_path)
        for entry in discovered.servers:
            entry.client = "Demo"
            entry.source = "mcp-bloat --demo (generated config)"
        results = asyncio.run(audit_all(discovered.servers, timeout=timeout))
        return results, discovered.warnings
